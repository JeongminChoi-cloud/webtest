const params = new URLSearchParams(window.location.search);
const slug = params.get("item") || "pink1";
const data = DETAIL_DATA[slug] || DETAIL_DATA.pink1;

const detailTitle = document.getElementById("detailTitle");
const designer = document.getElementById("designer");
const season = document.getElementById("season");
const description = document.getElementById("description");
const mainScroll = document.getElementById("mainScroll");
const thumbGrid = document.getElementById("thumbGrid");
const resetViewBtn = document.getElementById("resetViewBtn");
let isLookView = false;

detailTitle.textContent = data.title;
designer.textContent = data.designer;
season.textContent = data.season;
description.textContent = data.description;

function resetToStageView(){
  renderMainImages(data.mainImages);
  isLookView = false;
  thumbGrid.querySelectorAll(".thumb").forEach(t => t.classList.remove("active"));
}

function renderMainImages(images){
  mainScroll.innerHTML = "";

  images.forEach((src) => {
    const img = document.createElement("img");
    img.src = src;
    img.alt = "";
    img.className = "main-image";
    mainScroll.appendChild(img);
  });
}

function renderThumbs(images){
  thumbGrid.innerHTML = "";

  images.forEach((src, index) => {
    const img = document.createElement("img");
    img.src = src;
    img.alt = "";
    img.className = "thumb";

    if(index === 0){
      img.classList.add("active");
    }

    img.addEventListener("click", () => {
      renderMainImages([src]);
      isLookView = true;

      thumbGrid.querySelectorAll(".thumb").forEach(t => t.classList.remove("active"));
      img.classList.add("active");
    });

    thumbGrid.appendChild(img);
  });
}
resetViewBtn.addEventListener("click", () => {
  if(isLookView){
    resetToStageView();
  } else {
    window.location.href = "mainpage.html";
  }
});
renderMainImages(data.mainImages);
renderThumbs(data.thumbnails);